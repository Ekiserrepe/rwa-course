/**
 * build-course-data.mjs: derives three artefacts from the course modules.
 *
 *   src/data/generated/manifest.js  module + lesson metadata, bundled with the
 *                                   app so the overview renders with no fetch
 *   public/search/<lang>.json       stripped lesson bodies, fetched the first
 *                                   time someone opens search
 *   public/sitemap.xml              one entry per lesson deep link
 *   public/robots.txt               points crawlers at the sitemap
 *   public/CNAME                    the custom domain, when the site owns one
 *
 * Why: courses.js used to import all twelve modules statically, so every
 * visitor downloaded the entire curriculum (~3.1 MB of JS) before the index
 * page painted. Splitting metadata from content lets the modules load on
 * demand, and moving search to a per-language index keeps full-text search
 * working without holding all eight translations in memory.
 *
 * Runs automatically via `npm run prebuild` / `predev`.
 */

import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

const { codeFile } = await import(path.join(ROOT, 'src/data/code-files.js'))

const { SITE_URL: SITE } = await import(path.join(ROOT, 'site.config.js'))

// ── 0. Example sources ──────────────────────────────────────────────────────
// Lessons show the scripts in /examples verbatim: modules reference them by
// path (EXAMPLES['02-mint.js']) instead of pasting a copy that would drift from
// the file people actually run. Must be written before the modules import it.

const EXAMPLES_DIR = path.join(ROOT, 'examples')
const EXAMPLE_EXT = /\.(js|c|sh|html)$|^term-sheet\.json$|^xahau\.toml$|^warehouse-deed\.txt$/
const SKIP = new Set(['node_modules', 'art', 'metadata', 'include'])

async function collectExamples(dir, prefix = '') {
  const out = {}
  for (const entry of (await readdir(dir, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
    if (SKIP.has(entry.name) || entry.name.startsWith('.')) continue
    const rel = prefix + entry.name
    if (entry.isDirectory()) Object.assign(out, await collectExamples(path.join(dir, entry.name), rel + '/'))
    else if (EXAMPLE_EXT.test(entry.name)) out[rel] = await readFile(path.join(dir, entry.name), 'utf8')
  }
  return out
}

const examples = await collectExamples(EXAMPLES_DIR)
await mkdir(path.join(ROOT, 'src/data/generated'), { recursive: true })
await writeFile(
  path.join(ROOT, 'src/data/generated/examples.js'),
  `// GENERATED by scripts/build-course-data.mjs from /examples. Do not edit by hand.\n` +
    `export const EXAMPLES = ${JSON.stringify(examples, null, 1)}\n`,
)

const { MODULE_FILES } = await import(path.join(ROOT, 'src/data/module-list.js'))
const { LOCALES } = await import(path.join(ROOT, 'src/data/locales.js'))

/** Markdown is for reading, not matching: flatten it for the search body. */
function plain(text) {
  return String(text ?? '')
    .replace(/```[\s\S]*?```/g, ' ')           // fenced code: noise for prose search
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')   // [label](url) -> label
    .replace(/https?:\/\/\S+/g, ' ')
    .replace(/[#*`_>|]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

const modules = []
for (const file of MODULE_FILES) {
  const mod = (await import(path.join(ROOT, 'src/data/modules', file))).default
  modules.push({ file, mod })
}

// ── 1. Manifest ─────────────────────────────────────────────────────────────

const manifest = modules.map(({ file, mod }) => ({
  id: mod.id,
  file,
  icon: mod.icon,
  title: mod.title,
  lessons: mod.lessons.map((l) => ({
    id: l.id,
    title: l.title,
    hasCode: !!l.codeBlocks?.length,
    codeCount: l.codeBlocks?.length ?? 0,
    // Which examples/ files the Code tab shows, so theory can link to them
    files: (l.codeBlocks ?? []).map(codeFile),
    hasSlides: !!l.slides?.length,
  })),
}))

await mkdir(path.join(ROOT, 'src/data/generated'), { recursive: true })
await writeFile(
  path.join(ROOT, 'src/data/generated/manifest.js'),
  `// GENERATED by scripts/build-course-data.mjs. Do not edit by hand.\n` +
    `export const COURSE_MANIFEST = ${JSON.stringify(manifest, null, 0)}\n`,
)

// ── 2. Per-language search index ────────────────────────────────────────────

const pick = (field, code) => field?.[code] ?? field?.en ?? field?.es ?? ''

await mkdir(path.join(ROOT, 'public/search'), { recursive: true })
const sizes = []
for (const { code } of LOCALES) {
  const docs = []
  modules.forEach(({ mod }, mIdx) => {
    mod.lessons.forEach((lesson, lIdx) => {
      docs.push({
        m: mIdx,
        l: lIdx,
        mt: pick(mod.title, code),
        lt: pick(lesson.title, code),
        b: plain(pick(lesson.theory, code)),
      })
    })
  })
  const json = JSON.stringify(docs)
  await writeFile(path.join(ROOT, `public/search/${code}.json`), json)
  sizes.push(`${code} ${Math.round(json.length / 1024)}KB`)
}

// ── 3. Sitemap ──────────────────────────────────────────────────────────────

const urls = ['']
modules.forEach((m, mIdx) => {
  m.mod.lessons.forEach((_, lIdx) => urls.push(`?m=${mIdx}&l=${lIdx}`))
})

await writeFile(
  path.join(ROOT, 'public/sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>\n` +
    `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
    urls
      .map(
        (u) =>
          `  <url><loc>${SITE}/${u.replace(/&/g, '&amp;')}</loc>` +
          `<changefreq>monthly</changefreq>` +
          `<priority>${u === '' ? '1.0' : '0.7'}</priority></url>`,
      )
      .join('\n') +
    `\n</urlset>\n`,
)

// robots.txt has to name the sitemap's absolute URL, so it is generated from
// the same constant rather than left as a static file that can drift.
await writeFile(
  path.join(ROOT, 'public/robots.txt'),
  `User-agent: *\nAllow: /\n\nSitemap: ${SITE}/sitemap.xml\n`,
)

// GitHub Pages serves a custom domain only while the deployed site carries a
// CNAME file naming it. Derive it from SITE_URL too, so moving hosts can't
// leave a stale one behind; a *.github.io URL needs none.
const HOST = new URL(SITE).hostname
// Only a site at the root of its own domain may claim it. On a sub-path
// (learn.xahau.network/rwa-course) the domain belongs to whichever Pages site
// serves its root, and a CNAME here would try to take it over.
const CNAME = path.join(ROOT, 'public/CNAME')
const ownsDomain = new URL(SITE).pathname === '/' && !HOST.endsWith('.github.io')
if (ownsDomain) await writeFile(CNAME, `${HOST}\n`)
else await rm(CNAME, { force: true })

const lessons = manifest.reduce((n, m) => n + m.lessons.length, 0)
console.log(
  `course data: ${manifest.length} modules, ${lessons} lessons\n` +
    `  manifest  src/data/generated/manifest.js\n` +
    `  examples  ${Object.keys(examples).length} files from /examples\n` +
    `  search    ${sizes.join(', ')}\n` +
    `  sitemap   ${urls.length} urls at ${SITE}`,
)
